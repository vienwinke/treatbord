#!/usr/bin/env bash
# ============================================================================
# 文档过期表述守卫（CI 门禁之一）
#
# 为什么需要它：本仓库的文档数字曾经**整表过期** —— README 写 116 文件 / 34 接口 /
# 16 页面 / 93 用例 / V1~V8，实测却是 124 / 40 / 17 / 129 / V1~V12。
# 数字漂移的根因不是"写错了"，而是**没有任何机制在它漂移时报警**。这个脚本就是那个机制。
#
# 约定：
#   * **当前时态文档**里的数字必须与实测一致 —— 名单见下面 FILES。
#   * **历史审核报告**（FINAL_REVIEW / GO_LIVE_CHECKLIST）刻意保留成文当时的数字，
#     并已在顶部加「时点快照」标注，属有意为之，故**不参与检查**。
#
# ⚠️ 模式串必须留在这个脚本里，**不要内联回任何被检查的文档**：
#    否则守卫会匹配到它自己（这个坑已经踩过一次）。
#
# 用法： bash deploy/scripts/check-doc-staleness.sh     # 退出码非 0 即阻断
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")/../.." || exit 1

# 过期表述清单（当前值见注释，改文档时一并更新这里）
#   116 个 Java -> 124 | 7.1k 行 -> 7.9k | 16/15 个页面 -> 17 | 93 用例 -> 129
#   V1~V8 -> V1~V12 | 「14 张表全部含 deleted」-> 10/19 张不含
#   「(34 个接口)」/「共 **34 个接口**」-> 40（注意"平台侧 34 个接口"是正确表述，不要误伤）
PATTERNS='116 个 Java|7\.1k|16 个页面|15 个页面|93 个自动化测试用例|设计文档（8 份）|V1~V8|14 张表，全部含|（34 个接口）|共 \*\*34 个接口\*\*'

FILES=(
  README.md
  docs/API_DESIGN.md
  docs/DB_DESIGN.md
  docs/RUNBOOK.md
  docs/SECURITY_REVIEW.md
  docs/CONSISTENCY_CHECKLIST.md
)

hits="$(grep -rnE "$PATTERNS" "${FILES[@]}" || true)"
if [ -n "$hits" ]; then
  echo "::error::发现过期表述，请同步文档（若确需保留，请加「时点快照」标注并加入本脚本的排除名单）"
  echo "$hits"
  exit 1
fi
echo "文档过期表述自查通过：${#FILES[@]} 个当前时态文档，0 命中"
